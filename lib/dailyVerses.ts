/**
 * Returns a deterministic, daily-updating biblical verse based on the date.
 * Every day of the year naturally produces a unique scripture.
 */
export function getDailyVerse(dateStr?: string): {
  reference: string;
  text: string;
  book: string;
  dateLabel: string;
} {
  const targetDate = dateStr ? new Date(`${dateStr}T12:00:00`) : new Date();
  const year = targetDate.getFullYear();
  const startOfYear = new Date(year, 0, 1);
  const diffTime = targetDate.getTime() - startOfYear.getTime();
  const dayOfYear = Math.max(0, Math.floor(diffTime / (1000 * 60 * 60 * 24)));

  const verseIndex = dayOfYear % DAILY_BIBLE_VERSES.length;
  const verse = DAILY_BIBLE_VERSES[verseIndex];

  const dateLabel = targetDate.toLocaleDateString('pt-BR', {
    day: 'numeric',
    month: 'long',
  });

  return {
    reference: verse.reference,
    text: verse.text,
    book: verse.book,
    dateLabel,
  };
}
